// Lock is the row lock a store read takes in the unit of work's
// transaction.
type Lock int

// The lock modes.
const (
	// LockNone is a plain read.
	LockNone Lock = iota
	// LockWrite is what a write holds until commit: FOR SHARE on a taxpayer
	// (an archive waits, so nothing lands on an archived taxpayer) and FOR
	// NO KEY UPDATE on an input row (two writers of one row serialize).
	LockWrite
)

// List names a bounded list (ADR-0009 "Bounded lists").
type List int

// The bounded lists.
const (
	ListDeductions List = iota + 1
	ListSalaryStatements
)

// Taxpayer is what the annual inputs read about a taxpayer.
type Taxpayer struct {
	PersonType fiscal.PersonType
	Archived   bool
}

// HeldRegime is a regime the taxpayer holds or held: its window, the 625
// definitive option and the catalog definitions of its tax inputs.
type HeldRegime struct {
	Code  fiscal.RegimeCode
	Start domain.Period
	// End is the zero Period while the regime is open.
	End              domain.Period
	DefinitiveOption bool
	Definitions      []domain.InputDef
}

// ActiveIn reports whether the regime is held in some month of fiscalYear.
func (r HeldRegime) ActiveIn(fiscalYear int) bool {
	return r.Start.Year() <= fiscalYear && (r.End.IsZero() || r.End.Year() >= fiscalYear)
}

// Holds reports whether the regime is held in month of fiscalYear.
func (r HeldRegime) Holds(fiscalYear int, month time.Month) bool {
	at := monthIndex(fiscalYear, month)
	return monthIndex(r.Start.Year(), r.Start.Month()) <= at &&
		(r.End.IsZero() || at <= monthIndex(r.End.Year(), r.End.Month()))
}

// monthIndex orders (year, month) pairs.
func monthIndex(year int, month time.Month) int { return year*monthsPerYear + int(month) - 1 }

const monthsPerYear = 12

// AccessPolicy is the part of access.Policy (P0-16) the annual writes
// consume. It returns a client-ready *apperr.Error (402
// entitlement_required) for a read-only user.
type AccessPolicy interface {
	EnsureWritable(ctx context.Context, userID string) error
}

// TaxpayerStore reads the taxpayer and its regimes in the unit of work in
// ctx (RLS: another user's taxpayer is ErrTaxpayerNotFound).
type TaxpayerStore interface {
	// Taxpayer reads one taxpayer under lock; ErrTaxpayerNotFound.
	Taxpayer(ctx context.Context, taxpayerID string, lock Lock) (Taxpayer, error)
	// Regimes reads every regime the taxpayer holds or held, by code.
	Regimes(ctx context.Context, taxpayerID string) ([]HeldRegime, error)
	// LockRegime takes FOR NO KEY UPDATE on the taxpayer's regime row until
	// commit (two replaces of its filed payments serialize);
	// ErrRegimeNotHeld.
	LockRegime(ctx context.Context, taxpayerID string, code fiscal.RegimeCode) error
	// LockList serializes, until commit, the writers that may grow list for
	// the taxpayer and fiscal year, so a bound check and its insert are one
	// step.
	LockList(ctx context.Context, taxpayerID string, list List, fiscalYear int) error
}

// NullCents is a nullable amount; the zero value is null. It is
// comparable, which the idempotent replay relies on.
type NullCents struct {
	Cents money.Cents
	Valid bool
}

// DeductionFields are a personal deduction's persisted fields. The zero
// value of a nullable field is null ("" or an invalid NullCents).
type DeductionFields struct {
	Category      adomain.Category
	Amount        money.Cents
	PaidOn        fiscal.Date
	PaymentMethod adomain.PaymentMethod
	Beneficiary   adomain.Beneficiary
	DoneeType     adomain.DoneeType
	StudentLabel  string
	TuitionLevel  adomain.TuitionLevel
	Scholarship   NullCents
	// CFDIUUID is the folio in canonical upper case.
	CFDIUUID string
}

// Domain returns the deduction as the calculator reads it.
func (f DeductionFields) Domain() adomain.Deduction {
	return adomain.Deduction{
		Category: f.Category, Amount: f.Amount, PaymentMethod: f.PaymentMethod, Beneficiary: f.Beneficiary,
		DoneeType: f.DoneeType, Student: f.StudentLabel, TuitionLevel: f.TuitionLevel, Scholarship: f.Scholarship.Cents,
	}
}

// StoredDeduction is a personal_deductions row the caller may see, deleted
// or not. FiscalYear is the year of PaidOn (generated by the database).
type StoredDeduction struct {
	ID         string
	TaxpayerID string
	FiscalYear int
	DeductionFields
	Deleted   bool
	CreatedAt time.Time
	UpdatedAt time.Time
}

// NewDeduction is a deduction to insert.
type NewDeduction struct {
	ID         string
	UserID     string
	TaxpayerID string
	DeductionFields
}

// DeductionStore is personal_deductions in the unit of work in ctx.
type DeductionStore interface {
	// LockDeductionID serializes the creates of one client id until
	// commit: a double submit waits for the first, then finds it.
	LockDeductionID(ctx context.Context, id string) error
	// FindDeduction returns deduction id, deleted or not, under lock, or
	// ErrDeductionNotFound.
	FindDeduction(ctx context.Context, id string, lock Lock) (StoredDeduction, error)
	// InsertDeduction stores a new deduction, or ErrIDTaken when the id
	// exists (for any user: the primary key sees across RLS).
	InsertDeduction(ctx context.Context, d NewDeduction) error
	// UpdateDeduction replaces the fields of deduction id.
	UpdateDeduction(ctx context.Context, id string, f DeductionFields) error
	// SetDeductionDeleted soft-deletes (true) or restores (false) it.
	SetDeductionDeleted(ctx context.Context, id string, deleted bool) error
	// CountLiveDeductions counts the taxpayer's live deductions of the year.
	CountLiveDeductions(ctx context.Context, taxpayerID string, fiscalYear int) (int, error)
	// ListDeductions returns the taxpayer's live deductions of the year,
	// of one category ("" for all), in no particular order.
	ListDeductions(ctx context.Context, taxpayerID string, fiscalYear int, category adomain.Category) ([]StoredDeduction, error)
}

// SalaryFields are a salary constancia's persisted fields; an empty
// EmployerLabel is null.
type SalaryFields struct {
	FiscalYear          int
	EmployerLabel       string
	Accumulable         money.Cents
	Exempt              money.Cents
	ISRWithheld         money.Cents
	Simultaneous        bool
	LeftBeforeYearEnd   bool
	PayerNotWithholding bool
}

// Domain returns the constancia as the art. 152 strategy reads it.
func (f SalaryFields) Domain() adomain.SalaryStatement {
	return adomain.SalaryStatement{
		Accumulable: f.Accumulable, Exempt: f.Exempt, ISRWithheld: f.ISRWithheld, Simultaneous: f.Simultaneous,
		LeftBeforeYearEnd: f.LeftBeforeYearEnd, PayerNotWithholding: f.PayerNotWithholding,
	}
}

// StoredStatement is a salary_statements row the caller may see.
type StoredStatement struct {
	ID         string
	TaxpayerID string
	SalaryFields
	CreatedAt time.Time
	UpdatedAt time.Time
}

// NewStatement is a constancia to insert.
type NewStatement struct {
	ID         string
	UserID     string
	TaxpayerID string
	SalaryFields
}

// SalaryStore is salary_statements in the unit of work in ctx.
type SalaryStore interface {
	// LockStatementID serializes the creates of one client id until commit.
	LockStatementID(ctx context.Context, id string) error
	// FindStatement returns constancia id under lock, or
	// ErrStatementNotFound.
	FindStatement(ctx context.Context, id string, lock Lock) (StoredStatement, error)
	// InsertStatement stores a new constancia, or ErrIDTaken.
	InsertStatement(ctx context.Context, s NewStatement) error
	// UpdateStatement replaces the fields of constancia id.
	UpdateStatement(ctx context.Context, id string, f SalaryFields) error
	// DeleteStatement deletes constancia id.
	DeleteStatement(ctx context.Context, id string) error
	// CountStatements counts the taxpayer's constancias of the year.
	CountStatements(ctx context.Context, taxpayerID string, fiscalYear int) (int, error)
	// ListStatements returns the taxpayer's constancias of the year by
	// created_at, then id.
	ListStatements(ctx context.Context, taxpayerID string, fiscalYear int) ([]StoredStatement, error)
}

// Facts are the per-year annual facts (annual_inputs). A nil
// PriorYearAccumulableIncome is unknown, not zero (OQ-A5).
type Facts struct {
	PriorYearAccumulableIncome *money.Cents
	OtherExemptIncome          money.Cents
	ToldEmployerWillFile       bool
}

// Domain returns the facts as the art. 152 strategy reads them.
func (f Facts) Domain() adomain.PFAnnualInputs {
	return adomain.PFAnnualInputs{
		PriorYearAccumulableIncome: f.PriorYearAccumulableIncome,
		OtherExemptIncome:          f.OtherExemptIncome,
		ToldEmployerWillFile:       f.ToldEmployerWillFile,
	}
}

// StoredFacts is an annual_inputs row.
type StoredFacts struct {
	Facts
	UpdatedAt time.Time
}

// FactsStore is annual_inputs, and the money tax inputs it mirrors, in the
// unit of work in ctx.
type FactsStore interface {
	// Facts reads the row of the taxpayer and year; found is false when
	// nothing was saved (the defaults apply).
	Facts(ctx context.Context, taxpayerID string, fiscalYear int) (stored StoredFacts, found bool, err error)
	// UpsertFacts inserts or overwrites the row as userID's.
	UpsertFacts(ctx context.Context, userID, taxpayerID string, fiscalYear int, f Facts) error
	// TaxInputMoney reads the stored money values of keys for every regime
	// of the taxpayer in the year.
	TaxInputMoney(ctx context.Context, taxpayerID string, fiscalYear int, keys []domain.InputKey) (map[fiscal.RegimeCode]map[domain.InputKey]money.Cents, error)
}

// FiledMonth is one confirmed provisional payment.
type FiledMonth struct {
	Month  time.Month
	Amount money.Cents
}

// FiledKey names the filed payments of one taxpayer, regime and year: the
// set a PUT replaces.
type FiledKey struct {
	TaxpayerID string
	Regime     fiscal.RegimeCode
	FiscalYear int
}

// FiledStore is annual_filed_payments in the unit of work in ctx.
type FiledStore interface {
	// FiledMonths reads the confirmed months of key, by month, and the
	// latest updated_at among them (nil when there are none).
	FiledMonths(ctx context.Context, key FiledKey) ([]FiledMonth, *time.Time, error)
	// ReplaceFiled deletes every month of key and stores months as userID's.
	ReplaceFiled(ctx context.Context, userID string, key FiledKey, months []FiledMonth) error
}

// YearInputs are the annual-only inputs of one taxpayer and fiscal year as
// the annual estimate (ANN-14) reads them: the live personal deductions,
// the salary constancias and the per-year facts (the defaults when none
// were saved).
type YearInputs struct {
	Deductions       []adomain.Deduction
	SalaryStatements []adomain.SalaryStatement
	Facts            adomain.PFAnnualInputs
}

// YearInputsReader is the annual estimate's read port for YearInputs, in
// the estimate's unit of work (RLS).
type YearInputsReader interface {
	YearInputs(ctx context.Context, taxpayerID string, fiscalYear int) (YearInputs, error)
}

// FiledPaymentsReader is the annual estimate's read port for the payments
// the user confirmed (§2.5 source 1): every regime of the taxpayer in the
// year, month to amount; an absent month is not confirmed.
type FiledPaymentsReader interface {
	FiledPayments(ctx context.Context, taxpayerID string, fiscalYear int) (map[fiscal.RegimeCode]map[time.Month]money.Cents, error)
}
