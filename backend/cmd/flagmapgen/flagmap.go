package main

import (
	"bytes"
	"errors"
	"fmt"
	"go/format"
	"regexp"
	"slices"
	"strings"
	"text/template"

	"go.yaml.in/yaml/v3"
)

// Operation is one OpenAPI operation and the module (feature flag) that owns it.
type Operation struct {
	ID     string // operationId
	Method string // upper-case HTTP method
	Path   string
	Module string // x-module: "platform" or a module_<name> flag key
}

// Route is the net/http ServeMux pattern ("METHOD /path") the generated
// std-http server registers for the operation.
func (o Operation) Route() string { return o.Method + " " + o.Path }

// moduleKeyPattern mirrors rule/operation-x-module in redocly.yaml.
var moduleKeyPattern = regexp.MustCompile(`^(platform|module_[a-z][a-z_]*)$`)

// httpMethods are the path-item keys that hold an operation (OpenAPI 3.1 §4.8.9).
var httpMethods = []string{"get", "put", "post", "delete", "options", "head", "patch", "trace"}

// pathItemRefKey marks a path item defined elsewhere (OpenAPI 3.1 §4.8.9.1).
// flagmapgen does not resolve references, so it refuses them rather than
// silently omitting their operations from the flag map.
const pathItemRefKey = "$ref"

type specDocument struct {
	Paths map[string]map[string]yaml.Node `yaml:"paths"`
}

type specOperation struct {
	OperationID string `yaml:"operationId"`
	Module      string `yaml:"x-module"`
}

// ParseOperations reads an OpenAPI document and returns its operations sorted by
// operationId. Every operation must have an operationId (unique) and a valid
// x-module; all violations are reported together.
func ParseOperations(spec []byte) ([]Operation, error) {
	var doc specDocument
	if err := yaml.Unmarshal(spec, &doc); err != nil {
		return nil, fmt.Errorf("parse OpenAPI document: %w", err)
	}

	var (
		ops  []Operation
		errs []error
		seen = make(map[string]string) // operationId -> "METHOD /path"
	)
	for _, path := range sortedKeys(doc.Paths) {
		item := doc.Paths[path]
		if _, isRef := item[pathItemRefKey]; isRef {
			errs = append(errs, fmt.Errorf("%s: path item $ref is not supported; inline the operations so each one is gated", path))
			continue
		}
		for _, method := range httpMethods {
			node, ok := item[method]
			if !ok {
				continue
			}
			op, err := parseOperation(strings.ToUpper(method), path, &node)
			if err != nil {
				errs = append(errs, err)
				continue
			}
			where := op.Route()
			if first, dup := seen[op.ID]; dup {
				errs = append(errs, fmt.Errorf("%s: duplicate operationId %q (also on %s)", where, op.ID, first))
				continue
			}
			seen[op.ID] = where
			ops = append(ops, op)
		}
	}
	if err := errors.Join(errs...); err != nil {
		return nil, err
	}
	if len(ops) == 0 {
		return nil, errors.New("OpenAPI document has no operations")
	}
	slices.SortFunc(ops, func(a, b Operation) int { return strings.Compare(a.ID, b.ID) })
	return ops, nil
}

func parseOperation(method, path string, node *yaml.Node) (Operation, error) {
	where := method + " " + path
	var raw specOperation
	if err := node.Decode(&raw); err != nil {
		return Operation{}, fmt.Errorf("%s: decode operation: %w", where, err)
	}
	var errs []error
	if raw.OperationID == "" {
		errs = append(errs, fmt.Errorf("%s: missing operationId", where))
	}
	switch {
	case raw.Module == "":
		errs = append(errs, fmt.Errorf("%s (%s): missing x-module (platform or a module_<name> flag key)", where, raw.OperationID))
	case !moduleKeyPattern.MatchString(raw.Module):
		errs = append(errs, fmt.Errorf("%s (%s): x-module %q is neither platform nor a module_<name> flag key", where, raw.OperationID, raw.Module))
	}
	if err := errors.Join(errs...); err != nil {
		return Operation{}, err
	}
	return Operation{ID: raw.OperationID, Method: method, Path: path, Module: raw.Module}, nil
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	slices.Sort(keys)
	return keys
}

var fileTemplate = template.Must(template.New("flagmap").Parse(`// Code generated by flagmapgen from {{.Source}}. DO NOT EDIT.

package {{.Package}}

import "maps"

// ModulePlatform is the x-module of the always-on platform operations. They have
// no feature flag, so the flag gate never hides them.
const ModulePlatform = "platform"

// operationModules maps every operationId in the contract to its x-module.
var operationModules = map[string]string{
{{- range .Operations}}
	{{printf "%q" .ID}}: {{printf "%q" .Module}}, // {{.Method}} {{.Path}}
{{- end}}
}

// OperationModule returns the x-module of an operation: a module_<name> flag key,
// or ModulePlatform. ok is false for an operationId the contract does not declare.
func OperationModule(operationID string) (module string, ok bool) {
	module, ok = operationModules[operationID]
	return module, ok
}

// OperationModules returns a copy of the whole operationId -> x-module map.
func OperationModules() map[string]string {
	return maps.Clone(operationModules)
}

// routeModules maps every "METHOD /path" ServeMux pattern the generated server
// registers (empty BaseURL) to its x-module.
var routeModules = map[string]string{
{{- range .Routes}}
	{{printf "%q" .Route}}: {{printf "%q" .Module}}, // {{.ID}}
{{- end}}
}

// RouteModule returns the x-module of a matched route, keyed by the pattern
// net/http exposes as (*http.Request).Pattern. The flag gate uses it so a disabled
// module answers 404 before the strict handler decodes the request. (Strict
// middlewares receive the Go-normalized name, e.g. "GetHealth", not the
// operationId, and run after decoding.)
func RouteModule(pattern string) (module string, ok bool) {
	module, ok = routeModules[pattern]
	return module, ok
}
`))

// Render emits the gofmt-ed Go source of the operationId -> x-module map.
func Render(pkg, source string, ops []Operation) ([]byte, error) {
	routes := slices.Clone(ops)
	slices.SortFunc(routes, func(a, b Operation) int { return strings.Compare(a.Route(), b.Route()) })

	var buf bytes.Buffer
	data := struct {
		Package, Source    string
		Operations, Routes []Operation
	}{pkg, source, ops, routes}
	if err := fileTemplate.Execute(&buf, data); err != nil {
		return nil, fmt.Errorf("render flag map: %w", err)
	}
	src, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format flag map: %w", err)
	}
	return src, nil
}
